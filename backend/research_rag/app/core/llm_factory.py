"""
Single place that builds the chat model and embedding model for the whole
pipeline, based on settings.provider (gemini | ollama | test).
"""
from __future__ import annotations

import logging
import re
import threading
from typing import Any, List, Optional

from .settings import settings

logger = logging.getLogger(__name__)

_lock = threading.Lock()
_chat_llm = None
_embeddings = None


def _make_test_chat_model():
    from langchain_core.language_models.chat_models import SimpleChatModel

    class EchoChatModel(SimpleChatModel):
        """Deterministic stand-in for tests: answers with the first retrieved source."""

        @property
        def _llm_type(self) -> str:
            return "test-echo"

        def _call(self, messages: List[Any], stop: Optional[List[str]] = None, run_manager=None, **kwargs) -> str:
            prompt = str(messages[-1].content if messages else "")
            m = re.search(r"Source 0[^:\n]*:\s*(.+?)(?:\n\nSource 1|\n\s*Question:|$)", prompt, re.S)
            if m:
                sentences = [x for x in re.split(r"(?<=[.!?])\s+", m.group(1).strip()) if len(x.split()) >= 8]
                return " ".join(sentences[:2]).strip() or "Insufficient evidence."
            if "facts" in prompt.lower() or "paper '" in prompt.lower():
                return "## Test report\n\nGenerated by the test model from the indexed paper facts."
            return "standard"

    return EchoChatModel()


def get_chat_llm():
    """Returns the shared chat model (LangChain Runnable)."""
    global _chat_llm
    if _chat_llm is not None:
        return _chat_llm
    with _lock:
        if _chat_llm is not None:
            return _chat_llm
        provider = settings.provider
        if provider == "test":
            _chat_llm = _make_test_chat_model()
        elif provider == "gemini":
            from langchain_google_genai import ChatGoogleGenerativeAI

            logger.info("LLM: Gemini (%s)", settings.GEMINI_MODEL)
            _chat_llm = ChatGoogleGenerativeAI(
                model=settings.GEMINI_MODEL,
                google_api_key=settings.GOOGLE_API_KEY,
                temperature=0,
                timeout=120,
                max_retries=2,
            )
        else:
            from langchain_ollama import ChatOllama

            logger.info("LLM: Ollama (%s at %s)", settings.OLLAMA_MODEL, settings.OLLAMA_BASE_URL)
            _chat_llm = ChatOllama(model=settings.OLLAMA_MODEL, base_url=settings.OLLAMA_BASE_URL, temperature=0)
        return _chat_llm


def get_embeddings():
    """Returns the shared embedding model."""
    global _embeddings
    if _embeddings is not None:
        return _embeddings
    with _lock:
        if _embeddings is not None:
            return _embeddings
        provider = settings.provider
        if provider == "test":
            from langchain_core.embeddings import DeterministicFakeEmbedding

            _embeddings = DeterministicFakeEmbedding(size=256)
        elif provider == "gemini":
            from langchain_google_genai import GoogleGenerativeAIEmbeddings

            logger.info("Embeddings: Gemini (%s)", settings.GEMINI_EMBEDDING_MODEL)
            _embeddings = GoogleGenerativeAIEmbeddings(
                model=settings.GEMINI_EMBEDDING_MODEL,
                google_api_key=settings.GOOGLE_API_KEY,
            )
        else:
            try:
                from langchain_community.embeddings import HuggingFaceEmbeddings

                logger.info("Embeddings: local BAAI/bge-m3")
                _embeddings = HuggingFaceEmbeddings(model_name="BAAI/bge-m3", model_kwargs={"device": "cpu"})
            except Exception as exc:  # sentence-transformers missing or model download failed
                logger.warning("Local HF embeddings unavailable (%s); using Ollama %s", exc, settings.OLLAMA_EMBED_MODEL)
                from langchain_ollama import OllamaEmbeddings

                _embeddings = OllamaEmbeddings(model=settings.OLLAMA_EMBED_MODEL, base_url=settings.OLLAMA_BASE_URL)
        return _embeddings


def collection_name() -> str:
    """Vectors from different embedding models must never share a collection."""
    provider = settings.provider
    if provider == "gemini":
        return "papers_gemini_" + re.sub(r"[^a-z0-9]+", "_", settings.GEMINI_EMBEDDING_MODEL.lower()).strip("_")
    if provider == "test":
        return "papers_test"
    return "papers_local"
